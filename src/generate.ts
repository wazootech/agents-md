import { type Answers, withDefaults } from "./tree.ts";
import { rules, sectionOrder } from "./rules.ts";

/** Bump when rule text changes, so stale files can be spotted. */
export const RULESET_VERSION = 1;
export const SITE = "https://agents.wazoo.dev/";
export const LINE_BUDGET = 100;

export function encodeAnswers(a: Answers): string {
  const bytes = new TextEncoder().encode(JSON.stringify(a));
  let bin = "";
  for (const b of bytes) bin += String.fromCharCode(b);
  return btoa(bin).replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/, "");
}

export function decodeAnswers(s: string): Answers {
  try {
    const bin = atob(s.replaceAll("-", "+").replaceAll("_", "/"));
    const bytes = Uint8Array.from(bin, (c) => c.charCodeAt(0));
    const parsed = JSON.parse(new TextDecoder().decode(bytes));
    return parsed && typeof parsed === "object" ? parsed : {};
  } catch {
    return {};
  }
}

const todo = (what: string) => `TODO: ${what}`;

export function generate(input: Answers): string {
  const a = withDefaults(input);
  const out: string[] = [
    `<!-- Generated by ${SITE} (ruleset v${RULESET_VERSION}). Regenerate: ${SITE}#${
      encodeAnswers(input)
    } -->`,
    "",
    `# ${a.name || todo("project name")}`,
    "",
    a.summary || todo("one-line description"),
  ];

  for (const section of sectionOrder) {
    const lines: string[] = [];
    if (section === "Commands") {
      for (
        const [k, label] of [["build", "Build"], ["test", "Test"], [
          "lint",
          "Lint",
        ]]
      ) {
        lines.push(
          `- ${label}: ${a[k] ? `\`${a[k]}\`` : todo(`${k} command`)}`,
        );
      }
    } else {
      for (const r of rules) {
        if (r.section === section && (!r.when || r.when(a))) {
          lines.push(`- ${r.text}`);
        }
      }
    }
    if (lines.length) out.push("", `## ${section}`, "", ...lines);
  }

  return out.join("\n") + "\n";
}
